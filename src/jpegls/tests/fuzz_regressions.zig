fn sofDims(stream: []const u8) [2]u32 {
    const sof = util.find(stream, &.{ 0xFF, 0xF7 }).?;
    const h = std.mem.readInt(u16, stream[sof + 5 ..][0..2], .big);
    const w = std.mem.readInt(u16, stream[sof + 7 ..][0..2], .big);
    return .{ w, h };
}

fn expectErrvalRejected(stream_in: []const u8) !void {
    // Repair only the selector so these minimized malformed headers still
    // reach the corrupt entropy codes after selector validation was added.
    const stream = try ta.dupe(u8, stream_in);
    defer ta.free(stream);
    const sos = util.find(stream, &.{ 0xFF, 0xDA }).?;
    stream[sos + 5] = 1;
    var diag: jpegls.Diagnostic = .{};
    try util.expectErr(error.Truncated, util.decodeImageErrOpts(stream, .{ .diagnostic = &diag }));
    try testing.expect(diag.offset > sos);
    const wh = sofDims(stream);
    try util.expectErr(error.Truncated, util.decodeErr(stream, wh[0], wh[1]));
}

test "regular b errval out of range is rejected" {
    try expectErrvalRejected(&REGULAR_B_OVERFLOW);
}

test "regular a errval out of range is rejected" {
    try expectErrvalRejected(&REGULAR_A_OVERFLOW);
}

test "run a errval out of range is rejected" {
    try expectErrvalRejected(&RUN_A_OVERFLOW);
}

test "run recon errval out of range is rejected" {
    try expectErrvalRejected(&RUN_RECON_OVERFLOW);
}
